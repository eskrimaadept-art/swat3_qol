#!/usr/bin/env python3
# Generates src/stubs.h: for each DirectX interface the renderer implements, a base class whose
# every method (except IUnknown's) logs "UNIMPLEMENTED: Interface::Method" and fails. The real
# classes derive from these and override what the game uses.
# Usage: gen_stubs.py <include dir> <output file>
import re, sys
inc, out = sys.argv[1], sys.argv[2]
IFACES = {'ddraw.h': ['IDirectDraw', 'IDirectDraw2', 'IDirectDraw4', 'IDirectDraw7', 'IDirectDrawSurface3',
                      'IDirectDrawSurface4', 'IDirectDrawSurface7', 'IDirectDrawClipper'],
          'd3d.h': ['IDirect3D3', 'IDirect3DDevice3', 'IDirect3DViewport3', 'IDirect3DTexture2']}
res = ['// Generated by tools/gen_stubs.py - do not edit.', '#pragma once', '#include "common.h"',
       '#include <ddraw.h>', '#include <d3d.h>', '']
for hdr, names in IFACES.items():
    text = open(f'{inc}/{hdr}').read()
    for name in names:
        m = re.search(r'DECLARE_INTERFACE_\(\s*%s\s*,\s*(\w+)\s*\)\s*\{(.*?)\n\};' % name, text, re.S)
        if not m:
            sys.exit('interface not found: ' + name)
        body = re.sub(r'/\*.*?\*/', '', m.group(2), flags=re.S)
        decls = re.findall(r'STDMETHOD(_\(\s*(\w+)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\((.*?)\)\s*PURE\s*;', body, re.S)
        res.append(f'struct {name}Stub : public {name} {{')
        for d in decls:
            ret, meth = (d[1], d[2]) if d[1] else ('HRESULT', d[3])
            params = ' '.join(d[4].split())
            if meth in ('QueryInterface', 'AddRef', 'Release'):
                continue
            params = re.sub(r'^THIS_\s*', '', params)
            if params == 'THIS':
                params = ''
            fail = '0' if ret != 'HRESULT' else 'E_NOTIMPL'
            res.append(f'    {ret} STDMETHODCALLTYPE {meth}({params}) override {{ Unimpl("{name}::{meth}"); return {fail}; }}')
        res.append('};')
        res.append('')
open(out, 'w').write('\n'.join(res) + '\n')
print('wrote', out)
